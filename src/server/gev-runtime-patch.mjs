/**
 * Runtime preparation for the God's Eye View API on serverless hosts
 * (Vercel), where the function bundle is a single file in a read-only
 * directory and the repository layout is not on disk.
 *
 * Three things are true there that the endpoint module does not assume:
 *
 *   1. The process working directory is not writable. The module computes
 *      its disk-cache directories from `process.cwd()` (.gev-cache), so
 *      `process.cwd` is pointed at a per-instance temp directory.
 *
 *   2. Repo-anchored data files (data/, config/, the .gev-logs/ and
 *      .gev-cache/ directories, dist/) do not exist next to the bundle.
 *      Every fs call whose path contains one of those segments is
 *      remapped into the temp directory; the shipped files are seeded
 *      there first from src/server/embedded-data.mjs (regenerated by
 *      scripts/embed-server-data.mjs).
 *
 *   3. The `ws` package is an optional devDependency, absent from the
 *      function bundle. It is vendored (vendor/ws.cjs, regenerated with
 *      esbuild) and served through a Module._load interception, which is
 *      exactly what the module's lazy createRequire(...)('ws') loader
 *      resolves through.
 *
 * The patch is deliberately scoped to the segments the endpoint module
 * actually touches, so nothing else in the runtime is affected. Importing
 * this module is idempotent.
 *
 * NOTE: import this module BEFORE any module that imports
 * gev-endpoints.mjs — its top-level code computes the cache directories at
 * evaluation time.
 *
 * @module gev-runtime-patch
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { EMBEDDED_FILES } from './embedded-data.mjs';
import wsVendor from '../../vendor/ws.cjs';

const GLOBAL_FLAG = '__gevRuntimePatched';

/**
 * Map a path that references a repo-anchored data segment onto the writable
 * temp mirror. Returns the input unchanged for any other path.
 *
 * @param {string|URL|Buffer} p
 * @param {string} tmp
 * @returns {string|URL|Buffer}
 */
function remapPath(p, tmp) {
  if (typeof p !== 'string' || !p) return p;
  // Segment-boundary match so /mydata/foo or /configX never redirects.
  const match = p.match(/(^|\/)(data|config|\.gev-cache|\.gev-logs|dist)(?=\/|$)/);
  if (!match) return p;
  const relative = p.slice(match.index + match[1].length);
  return path.join(tmp, relative);
}

/** Wrap one fs method to remap its path argument. */
function wrapFsMethod(target, name, remap) {
  const original = target[name];
  if (typeof original !== 'function') return;
  target[name] = function patched(pathArg, ...rest) {
    return original.call(this, remap(pathArg), ...rest);
  };
}

if (!globalThis[GLOBAL_FLAG]) {
  globalThis[GLOBAL_FLAG] = true;

  const tmp = path.join(os.tmpdir(), 'gev');
  try {
    fs.mkdirSync(tmp, { recursive: true });
  } catch {
    // Temp dir unusable: caches degrade to memory only, reads fall through
    // to the ENOENT paths the endpoints already handle.
  }

  // 1) Writable working directory for the .gev-cache disk caches.
  try {
    process.cwd = () => tmp;
  } catch {
    /* keep the platform cwd */
  }

  // 2) Repo-anchored data segments → temp mirror, seeded from the bundle.
  try {
    for (const [relative, content] of EMBEDDED_FILES) {
      const target = path.join(tmp, relative);
      if (fs.existsSync(target)) continue;
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content, 'utf8');
    }
  } catch (error) {
    console.warn('[gev] could not seed embedded data files:', error?.message || error);
  }

  const remap = (p) => remapPath(p, tmp);
  const PROMISE_METHODS = [
    'readFile', 'writeFile', 'appendFile', 'copyFile', 'stat', 'lstat',
    'access', 'mkdir', 'rm', 'rename', 'readdir', 'open', 'unlink',
    'link', 'symlink', 'truncate', 'utimes',
  ];
  const SYNC_METHODS = [
    'readFileSync', 'writeFileSync', 'appendFileSync', 'copyFileSync',
    'statSync', 'lstatSync', 'accessSync', 'mkdirSync', 'rmSync',
    'renameSync', 'readdirSync', 'openSync', 'unlinkSync', 'linkSync',
    'symlinkSync', 'existsSync', 'truncateSync', 'utimesSync', 'cpSync',
  ];
  for (const name of PROMISE_METHODS) wrapFsMethod(fs.promises, name, remap);
  for (const name of SYNC_METHODS) wrapFsMethod(fs, name, remap);

  // 3) Serve the vendored `ws` to the module's lazy loader.
  try {
    const Module = createRequire(import.meta.url)('node:module');
    const originalLoad = Module._load;
    Module._load = function patchedLoad(request, parent, isMain) {
      if (request === 'ws') return wsVendor;
      return originalLoad.call(this, request, parent, isMain);
    };
  } catch (error) {
    console.warn('[gev] could not patch the ws loader:', error?.message || error);
  }

  console.log('[gev] serverless runtime prepared (writable mirror at', tmp + ')');
}
